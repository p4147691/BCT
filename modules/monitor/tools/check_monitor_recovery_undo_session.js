"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,".."),c={};
vm.runInNewContext(fs.readFileSync(path.join(root,"extension/monitor-recovery-undo-session.js"),"utf8"),{globalThis:c});
const html=fs.readFileSync(path.join(root,"extension/desktop.html"),"utf8");
const parts=fs.readFileSync(path.join(root,"source-parts/01-notes-history.js"),"utf8");
const domain=fs.readFileSync(path.join(root,"domains/desktop-lifecycle.js"),"utf8");
assert.ok(html.indexOf('src="monitor-recovery-undo-session.js"')<html.indexOf('src="monitor.js"'));
assert.match(parts,/MonitorRecoveryUndoSession[.]create/);
assert.doesNotMatch(parts,/const monitorUndoStack =/);
assert.doesNotMatch(domain,/resetDesktopUndoSessionExpiry/);
const create=c.MonitorRecoveryUndoSession.create;
assert.throws(()=>create({maxEntries:0,ttlMs:1000}),/requires/);
const u=create({maxEntries:2,ttlMs:10000});
assert.equal(u.peek(0),null);
u.push({kind:"A"},100);
u.push({kind:"B"},200);
u.push({kind:"C"},300);
assert.equal(u.peek(300).kind,"C");
assert.equal(u.remainingMs(300),10000);
u.pop(400);
assert.equal(u.peek(400).kind,"B");
assert.equal(u.remainingMs(400),10000);
assert.equal(u.expire(10399),false);
assert.equal(u.expire(10400),true);
assert.equal(u.peek(10400),null);
assert.equal(u.remainingMs(10400),0);
u.push({kind:"D"},20000);
assert.equal(u.peek(30000),null);
u.push({kind:"E"},40000);
u.pop(40010);
assert.equal(u.peek(40011),null);
console.log("PASS: isolated recovery undo owner, max stack, TTL, peek, pop, expiry");
