"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,".."),g={};
vm.runInNewContext(fs.readFileSync(path.join(root,"extension/monitor-desktop-frame-generation.js"),"utf8"),{globalThis:g});
const html=fs.readFileSync(path.join(root,"extension/desktop.html"),"utf8");
const domain=fs.readFileSync(path.join(root,"domains/desktop-lifecycle.js"),"utf8");
const part=fs.readFileSync(path.join(root,"source-parts/06-capture-preview.js"),"utf8");
assert.ok(html.indexOf('src="monitor-desktop-frame-generation.js"')<html.indexOf('src="monitor.js"'));
assert.match(domain,/monitorDesktopFrameGenerationController[.]invalidate[(]desktopIds[)]/);
assert.match(domain,/monitorDesktopFrameGenerationController[.]generation[(]desktopId[)]/);
assert.doesNotMatch(part,/let monitorFrameGeneration/);
const a=g.MonitorDesktopFrameGeneration.create();
assert.equal(a.generation("D1"),"0.0");
assert.equal(a.generation("D2"),"0.0");
const affected=a.invalidate(["D1","D1"]);
assert.equal(affected.size,1);
assert.equal(a.generation("D1"),"0.1");
assert.equal(a.generation("D2"),"0.0");
a.invalidate(["D2"]);
assert.equal(a.generation("D2"),"0.1");
a.invalidate([]);
assert.equal(a.generation("D1"),"1.0");
assert.equal(a.generation("D2"),"1.0");
assert.equal(g.MonitorDesktopFrameGeneration.create().generation("D1"),"0.0");
console.log("PASS: per-desktop and global frame invalidation generation with private owners");
