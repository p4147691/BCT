"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,".."),ctx={globalThis:null,Set,Number,String,Object};
ctx.globalThis=ctx;vm.createContext(ctx);
const source=fs.readFileSync(path.join(root,"extension/monitor-node-panel-interaction-state.js"),"utf8");
const parts=fs.readFileSync(path.join(root,"source-parts/05-native-lifecycle.js"),"utf8");
vm.runInContext(source,ctx);
assert.match(parts,/MonitorNodePanelInteractionState[.]create/);
assert.doesNotMatch(parts,/const monitorBctCollapsedScopes|let monitorBctSuppressedClickKey|let monitorBctSuppressScopeClickUntil/);
const state=ctx.MonitorNodePanelInteractionState.create();
assert.equal(state.isCollapsed("scope-a"),false);
assert.equal(state.toggleCollapsed("scope-a"),true);
assert.equal(state.isCollapsed("scope-a"),true);
assert.equal(state.toggleCollapsed("scope-a"),false);
state.setSuppressedKey("i:s:window:tab");
assert.equal(state.consumeSuppressedKey("wrong"),false);
assert.equal(state.getSuppressedKey(),"i:s:window:tab");
assert.equal(state.consumeSuppressedKey("i:s:window:tab"),true);
assert.equal(state.getSuppressedKey(),"");
state.setScopeSuppressedUntil(1000);
assert.equal(state.isScopeSuppressed(999),true);
assert.equal(state.isScopeSuppressed(1000),false);
assert.equal(ctx.MonitorNodePanelInteractionState.create().isCollapsed("scope-a"),false);
console.log("PASS: NodePanel owns independent collapsed network, exact click suppression and drag deadline");
