"use strict";
const assert=require("node:assert/strict");
require("../extension/monitor-wallpaper-state.js");
const x=globalThis.MonitorWallpaperState;
const one=x.begin("D1"),two=x.begin("D2");
assert.equal(one.status,"pending");
assert.equal(x.resolve("D1",one.generation,{ok:true,dataUri:"data:image/png;base64,REAL"},10).status,"captured");
const newer=x.onChange("D1");
assert.equal(x.current("D1").source,"","old pixels disappear immediately");
assert.equal(x.resolve("D1",one.generation,{ok:true,dataUri:"data:image/png;base64,OLD"}).applied,false);
const failed=x.resolve("D1",newer.generation,{ok:false,error:"Native unavailable"});
assert.equal(failed.status,"failed");assert.equal(failed.source,"");
assert.equal(x.current("D2").generation,two.generation,"other desktop untouched");
const recovered=x.onChange("D1");
assert.equal(x.resolve("D1",recovered.generation,{ok:true,dataUri:"data:image/jpeg;base64,NEW"},20).status,"captured");
x.discard("D1");assert.equal(x.current("D1"),null);
console.log("PASS wallpaper pure lifecycle: changed, invalidated, failed, recovered, stale denied, desktop isolated");
