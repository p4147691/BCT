"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const root=path.join(__dirname,"..");
const file=JSON.parse(fs.readFileSync(path.join(root,"native","com.pas40.desktop_window_monitor.json"),"utf8"));
const control=JSON.parse(fs.readFileSync(path.join(root,"native","com.pas40.desktop_window_monitor_control.json"),"utf8"));
const allowed=["chrome-extension://kaigandfpieiogfbfaemoimenmipedck/"];
assert.equal(file.name,"com.pas40.desktop_window_monitor");
assert.equal(control.name,"com.pas40.desktop_window_monitor_control");
assert.equal(file.type,"stdio");assert.equal(control.type,"stdio");
assert.deepEqual(file.allowed_origins,allowed);assert.deepEqual(control.allowed_origins,allowed);
assert.notEqual(file.path.toLowerCase(),control.path.toLowerCase());
assert.match(file.path,/1\.9\.20\.128-hidden-all[\\/]DesktopWindowMonitorHost\.exe$/i,"file shell contract is implemented by the retained original host");
assert.match(control.path,/native[\\/]1\.9\.20\.\d+-[^\\/]+[\\/]DesktopWindowMonitorControlHost\.exe$/i,
  "native virtual desktop controller must use a versioned control-host release directory");
const background=fs.readFileSync(path.join(root,"extension","background.js"),"utf8");
const js=fs.readFileSync(path.join(root,"extension","monitor.js"),"utf8");
const publish=fs.readFileSync(path.join(root,"tools","Publish-MonitorDeployment.ps1"),"utf8");
assert.match(background,/const HOST_NAME = "com\.pas40\.desktop_window_monitor"/);
assert.match(background,/response\?\.event === true\) return;/,"unsolicited events cannot consume file shell requests");
assert.match(js,/const MONITOR_CONTROL_HOST = "com\.pas40\.desktop_window_monitor_control"/);
assert.match(publish,/check_monitor_native_host_roles\.py/);
assert.match(publish,/--probe/,"Windows deployment gate performs real read-only list and virtual desktop query");
console.log("PASS: file-shell and controller native messaging manifests distinct, origin scoped, dual read-only prepublish probe enabled");
