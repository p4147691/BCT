"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const root=path.resolve(__dirname,".."),ctx={globalThis:null,Object,Number,String};
ctx.globalThis=ctx;vm.createContext(ctx);
const src=fs.readFileSync(path.join(root,"extension/monitor-desktop-stage-view.js"),"utf8");
const domain=fs.readFileSync(path.join(root,"domains/desktop-lifecycle.js"),"utf8");
const html=fs.readFileSync(path.join(root,"extension/desktop.html"),"utf8");
vm.runInContext(src,ctx);
assert(html.indexOf('src="monitor-desktop-stage-view.js"')<html.indexOf('src="monitor.js"'));
assert.match(domain,/monitorDesktopStageView[.]showTopology/);
assert.match(domain,/monitorDesktopStageView[.]showPreview/);
assert.doesNotMatch(domain,/document[.]body[.]dataset[.]monitor(?:ActiveDesktopId|HostDesktopId|ObservedDesktopId|PreviewDesktop)/);
assert.doesNotMatch(src,/chrome[.]|monitorNative|actFetch/);
const classes=new Set(),body={dataset:{},classList:{toggle:(x,on)=>on?classes.add(x):classes.delete(x)}};
const view=ctx.MonitorDesktopStageView.create({body});
const state={currentDesktopId:"d1",hostDesktopId:"host",observedDesktopId:"d2",currentIndex:0,selectedIndex:1};
const snapshot=view.showTopology(state);
assert.equal(body.dataset.monitorActiveDesktopId,"d1");
assert.equal(body.dataset.monitorHostDesktopId,"host");
assert.equal(body.dataset.monitorObservedDesktopId,"d2");
assert.equal(body.dataset.monitorPreviewDesktop,"2");
assert(classes.has("monitor-preview-remote"));
view.showPreview({desktopId:"d1",index:0,currentIndex:0});
assert.equal(body.dataset.monitorObservedDesktopId,"d1");
assert.equal(body.dataset.monitorPreviewDesktop,"1");
assert(!classes.has("monitor-preview-remote"));
assert.equal(snapshot.previewIndex,1);
assert.throws(()=>ctx.MonitorDesktopStageView.create({}),/DESKTOP_STAGE_DOM_REQUIRED/);
console.log("PASS: DesktopStage owns current/host/observed GUID and D1/D2 preview DOM state");
