"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path"),vm=require("node:vm");
const source=fs.readFileSync(path.join(__dirname,"../extension/background.js"),"utf8");
const start=source.indexOf("let desktopShellNativePort = null;");
const end=source.indexOf("function normalizeDesktopSessions(",start);
assert(start>0&&end>start,"desktop Native channel is isolated");
let onMessage=null,onDisconnect=null,connectCount=0;
const sent=[];
const port={onMessage:{addListener(fn){onMessage=fn}},onDisconnect:{addListener(fn){onDisconnect=fn}},postMessage(payload){sent.push(payload)}};
const context={HOST_NAME:"com.pas40.desktop_window_monitor",chrome:{runtime:{connectNative:()=>{connectCount++;return port},lastError:{message:"disconnect"}}},Promise,Error};
vm.createContext(context);
vm.runInContext(source.slice(start,end)+";globalThis.test={sendToHelper, pending:desktopShellNativePending};",context);
const x=context.test;
(async()=>{
 let settled=false;
 const task=x.sendToHelper({type:"list",includeVisuals:false}).then(res=>{settled=true;return res});
 assert.equal(sent.length,1);assert.equal(x.pending.length,1);
 onMessage({event:true,type:"desktopWallpaperChanged",at:123});
 await Promise.resolve();
 assert.equal(settled,false,"unsolicited wallpaper signal must not complete file-list request");
 assert.equal(x.pending.length,1,"wallpaper event cannot shift FIFO");
 onMessage({ok:true,items:[{path:"sample.txt"}]});
 const list=await task;
 assert.equal(list.ok,true);assert.equal(list.items.length,1);assert.equal(x.pending.length,0);
 assert.equal(connectCount,1,"connected native port is reused");
 onMessage({event:true,type:"windowMoveSizeEnd",hwnd:"123"});
 assert.equal(x.pending.length,0);
 const task2=x.sendToHelper({type:"listDirectory",path:"C:\\test"});
 assert.equal(x.pending.length,1);
 onMessage({event:true,type:"desktopWallpaperChanged",at:456});
 assert.equal(x.pending.length,1);
 onMessage({ok:false,error:"REAL_LIST_ERROR"});
 assert.equal((await task2).error,"REAL_LIST_ERROR","actual Native error response is not suppressed");
 const task3=x.sendToHelper({type:"list",includeVisuals:false});
 assert.equal(x.pending.length,1);
 onDisconnect();
 await assert.rejects(task3,/Desktop file host|disconnect|lost/i);
 assert.equal(x.pending.length,0,"disconnect empties queue");
 console.log("PASS: unsolicited wallpaper/window events never consume Native file list replies; success/error/disconnect and port reuse retained");
})().catch(e=>{console.error(e);process.exitCode=1});
