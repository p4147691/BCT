"use strict";
const assert=require("node:assert/strict"),fs=require("node:fs"),path=require("node:path");
const root=path.join(__dirname,"..");
const read=name=>fs.readFileSync(path.join(root,name),"utf8");
const host=read("native/src/MonitorDesktopHost.cs");
const drop=read("native/src/MonitorExternalWindowDrop.cs");
const lifecycle=read("domains/desktop-lifecycle.js");
const transport=read("domains/native-transport.js");
const css=read("extension/monitor.css");

assert.match(host,/setExternalWindowDropTargets/) ;
assert.match(host,/MonitorExternalWindowDrop\.OnMoveStart\(hWnd\)/);
assert.match(host,/MonitorExternalWindowDrop\.OnMoveLocation\(hWnd\)/);
assert.match(host,/MonitorExternalWindowDrop\.OnMoveEnd\(hWnd\)/);
assert.match(host,/private static object MoveWindowToDesktop\(Dictionary<string, object> request\)/);
assert.match(host,/internal static object MoveExternalWindowToDesktop\(Dictionary<string, object> request\)\s*\{\s*return MoveWindowToDesktop\(request\);\s*\}/s);
assert.match(drop,/GetCursorPos/);
assert.match(drop,/DwmSetWindowAttribute/);
assert.match(drop,/ExternalGlowOverlay/);
assert.match(drop,/Opacity = .16/);
assert.doesNotMatch(drop,/Color.Magenta|TransparencyKey/);
assert.match(drop,/HtTransparent/);
assert.match(drop,/MoveExternalWindowToDesktop/);
assert.match(drop,/externalWindowDropFinished/);
