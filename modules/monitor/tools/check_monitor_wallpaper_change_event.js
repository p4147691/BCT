"use strict";
const fs=require("fs"),assert=require("node:assert/strict"),vm=require("node:vm");
const js=fs.readFileSync("modules/monitor/extension/monitor.js","utf8");
const native=fs.readFileSync("modules/monitor/native/src/MonitorDesktopHost.cs","utf8");
assert.match(native,/StartWallpaperChangeEvents\(\);/);
const registryWatcher=fs.readFileSync("modules/monitor/native/src/MonitorWallpaperRegistryWatcher.cs","utf8");
assert.match(native,/MonitorWallpaperRegistryWatcher\.Start\(/,"Native startup must use the OS registry watcher");
assert.doesNotMatch(native,/SystemEvents\.UserPreferenceChanged\s*\+=/,"no unreliable wallpaper-only Windows 11 event dependency");
assert.match(registryWatcher,/RegNotifyChangeKeyValue\(/,"blocking registry notifications, not polling");
assert.match(registryWatcher,/VirtualDesktops\\Desktops/,"per-virtual-desktop wallpaper key watched");
assert.match(registryWatcher,/Control Panel\\Desktop/,"global wallpaper key watched");
assert.doesNotMatch(registryWatcher,/setInterval|Timer\s*\(/,"no polling");
assert.match(native,/"type", "desktopWallpaperChanged"/);
const start=js.indexOf('    if (response?.event === true && response?.type === "desktopWallpaperChanged")');
const end=js.indexOf('    if (response?.event === true && response?.type === "monitorDragPreviewReleased")',start);
assert(start>0&&end>start);
const branch=js.slice(start,end);
const calls=[],cache=new Map([["D1",{}],["D2",{}],["D3",{}]]),actual=new Map(cache);
const visuals=["D1","D2"].map(desktopId=>({dataset:{desktopId},style:{backgroundImage:"old"}}));
const thumbs={dataset:{},querySelectorAll:()=>visuals};
const preview={dataset:{desktopId:"D1"},style:{backgroundImage:"old"}};
const adapter={notify:({desktopIds,invalidate,display,onObserved})=>{for(const id of desktopIds){calls.push(id);invalidate(id);display(id,"data:image/png;base64,NEW",{desktopId:id,status:"captured",reason:""});onObserved({desktopId:id,status:"captured",reason:""})}return Promise.resolve()}};
const env={response:{event:true,type:"desktopWallpaperChanged"},monitorDesktopState:{currentDesktopId:"D2",desktopIds:["D1","D2","D3"],selectedIndex:0},monitorDesktopThumbs:thumbs,monitorPreviewWallpaper:preview,monitorWallpaperActuals:actual,monitorWallpaperCache:cache,globalThis:{MonitorWallpaperEventRefresh:adapter},Date,JSON};
vm.runInNewContext("(function(){"+branch+"})()",env);
assert.deepEqual(calls,["D1","D2"],"Windows-current and Monitor-selected differ, both visible desktop backgrounds are refreshed");
assert.equal(cache.has("D1"),false);assert.equal(actual.has("D2"),false);
assert.equal(cache.has("D3"),true);assert.equal(actual.has("D3"),true);
assert.match(preview.style.backgroundImage,/NEW/);
assert.equal(thumbs.dataset.wallpaperLastDesktopId,"D2");
console.log("PASS: wallpaper signal updates visible desktop backgrounds, not only Windows current ID");
