"use strict";
const assert = require("node:assert/strict"), fs = require("node:fs"), path = require("node:path"), vm = require("node:vm");
const root = path.resolve(__dirname, ".."), ctx = {};
vm.runInNewContext(fs.readFileSync(path.join(root, "extension/monitor-node-panel-selection.js"), "utf8"), {globalThis: ctx});
const html = fs.readFileSync(path.join(root, "extension/desktop.html"),"utf8");
const nodeSource = fs.readFileSync(path.join(root,"domains/node-identity.js"),"utf8");
const nativeSource = fs.readFileSync(path.join(root,"source-parts/03-node-activity.js"),"utf8");
assert.ok(html.indexOf('src="monitor-node-panel-selection.js"') < html.indexOf('src="monitor.js"'));
assert.match(nativeSource,/const monitorNodePanelSelection =/);
assert.doesNotMatch(nativeSource,/let monitorBctSelectedNodeKey/);
assert.doesNotMatch(nodeSource,/monitorBctSelectedNodeKey/);
assert.match(nodeSource,/monitorNodePanelSelection[.]key[(]value[)]/);
const sel = ctx.MonitorNodePanelSelection.create();
const exact = {instanceId:"instance", sessionId:"session", windowId:"18",tabId:"22"};
assert.equal(sel.key(exact),"instance:session:18:22");
assert.equal(sel.key({windowId:"18",tabId:"22"}),"tab:18:22");
assert.equal(sel.key({windowId:"18"}),"");
assert.equal(sel.get(),"");
assert.equal(sel.matches(exact),false);
sel.set(sel.key(exact));
assert.equal(sel.matches(exact),true);
assert.equal(sel.matches({windowId:"18",tabId:"22"}),false);
const other = ctx.MonitorNodePanelSelection.create();
assert.equal(other.get(),"");
sel.clear();
assert.equal(sel.get(),"");
assert.equal(sel.matches(exact),false);
console.log("PASS: private exact RCC node UI selection state, identity, isolation, clear");
