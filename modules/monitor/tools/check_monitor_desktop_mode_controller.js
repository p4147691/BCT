"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const root = path.resolve(__dirname, "..");
const context = {};
vm.runInNewContext(fs.readFileSync(path.join(root, "extension/monitor-desktop-mode-controller.js"), "utf8"), {globalThis:context});
const html = fs.readFileSync(path.join(root, "extension/desktop.html"), "utf8");
const domain = fs.readFileSync(path.join(root, "domains/desktop-lifecycle.js"), "utf8");
const parts = fs.readFileSync(path.join(root, "source-parts/01-notes-history.js"), "utf8");
assert.ok(html.indexOf('src="monitor-desktop-mode-controller.js"') < html.indexOf('src="monitor.js"'));
assert.match(domain, /monitorDesktopModeController[.]set[(]/);
assert.match(domain, /monitorDesktopModeController[.]get[(]/);
assert.doesNotMatch(parts, /let monitorDesktopManagementModes/);

const saved = [];
const api = context.MonitorDesktopModeController.create({persist: snapshot => saved.push({...snapshot})});
assert.equal(api.get("D1"),"OBSERVE_ONLY");
api.hydrate({" D1 ": "managed", "D2":"PROTECTED", "D3":"INVALID", "":"MANAGED"});
assert.equal(api.get("D1"),"MANAGED");
assert.equal(api.get("D2"),"PROTECTED");
assert.equal(api.get("D3"),"OBSERVE_ONLY");
assert.equal(api.next("MANAGED"),"PROTECTED");
assert.equal(api.next("PROTECTED"),"OBSERVE_ONLY");
assert.equal(api.next("OBSERVE_ONLY"),"MANAGED");
assert.equal(api.set("", "MANAGED"),false);
assert.equal(api.set("D1", "BOGUS"),false);
assert.equal(api.set("D1", "MANAGED"),false);
assert.equal(saved.length,0);
assert.equal(api.set("D1","PROTECTED"),true);
assert.equal(saved.length,1);
assert.equal(saved[0].D1,"PROTECTED");
assert.equal(api.get("D1"),"PROTECTED");
assert.equal(Object.isFrozen(api.snapshot()),true);
assert.throws(()=>context.MonitorDesktopModeController.create(),/persistence/);
console.log("PASS: desktop management state owner, storage injection, validation and idempotence");
